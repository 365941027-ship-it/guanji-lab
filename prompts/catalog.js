// 站内真实存在的入口清单。
//
// 为什么需要这个文件：Agent 的提示词里写了「结尾必须推荐另一个具体测试名称」，
// 但提示词本身并不知道站内到底有哪几个测试。实测中模型会推荐
// 「VIA 24 项性格优势测试」这类站内并不存在的测试，用户点不到，体验是断的。
// 所以这里把真实清单作为「事实」统一追加到每个 Agent 的系统提示词后面，
// 让推荐一定落在用户真的能打开的地方（原始提示词原文不改动）。

// 六大核心测试（与 tests.html / index.html 的卡片一一对应）
export const CORE_TESTS = [
  { name: '我如何成为我', for: '想弄清楚「我是谁、正处在什么阶段」的人' },
  { name: '我的能量地图', for: '总是内耗、疲惫，想找到自己充电方式的人' },
  { name: '我在关系里的位置', for: '在亲密关系、付出与边界上反复受困的人' },
  { name: '我的天赋信号', for: '想找到自己真正擅长什么、心流在哪的人' },
  { name: '我如何重新生长', for: '刚经历过低谷，想知道自己靠什么撑住的人' },
  { name: '我真正想要的生活', for: '在工作、自由与满意之间犹豫的人' }
];

// 站内其他可引导的入口
export const OTHER_ENTRIES = [
  '人生设计（根据你的档案与测试结果，生成三条具体的人生原型）',
  '人生模拟（在某个原型里预演真实职业中的选择，看看会走向哪里）',
  '我的专属自查（基于你最新的测试与记录，每次重新生成的问题）',
  '成长轨迹 / 三十天陪伴（记录今天，看见自己的变化）'
];

/**
 * 生成追加到系统提示词末尾的「事实块」。
 * 用词刻意保持中性：它是资料，不是新的写作要求。
 */
export function buildCatalogBlock() {
  const tests = CORE_TESTS.map((t) => `- ${t.name}：适合${t.for}`).join('\n');
  const others = OTHER_ENTRIES.map((t) => `- ${t}`).join('\n');
  return [
    '【站内真实存在的入口 · 事实资料】',
    '推荐测试或下一步时，只能从下面这份清单里选，并使用清单里的原名；',
    '不要推荐清单之外的测试或量表（例如站内没有的 VIA、霍兰德、MBTI 官方测试等）。',
    '',
    '六个核心测试：',
    tests,
    '',
    '其他可以引导的入口：',
    others,
    '',
    '如果这几个测试都不贴合对方当下的处境，就引导 ta 去「人生设计」，而不要硬推荐一个不相关的测试。'
  ].join('\n');
}

export default buildCatalogBlock;
